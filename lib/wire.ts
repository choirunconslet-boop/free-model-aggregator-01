/** Read one SSE stream as frames: each frame's event name and its parsed JSON data. */
async function* sseFrames(upstream: ReadableStream<Uint8Array>): AsyncGenerator<{ event: string | null; data: unknown }> {
  const reader = upstream.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  try {
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      buffer += decoder.decode(value, { stream: true }).replace(/\r\n/g, '\n');
      let at = buffer.indexOf('\n\n');
      while (at !== -1) {
        const frame = buffer.slice(0, at);
        buffer = buffer.slice(at + 2);
        let event: string | null = null;
        const dataLines: string[] = [];
        for (const line of frame.split('\n')) {
          if (line.startsWith('event:')) event = line.slice(6).trim();
          else if (line.startsWith('data:')) dataLines.push(line.slice(5).replace(/^ /, ''));
        }
        if (dataLines.length === 0) continue;
        const raw = dataLines.join('\n').trim();
        if (raw === '[DONE]') {
          yield { event, data: '[DONE]' };
          continue;
        }
        try {
          yield { event, data: JSON.parse(raw) };
        } catch {
          // A frame that is not JSON carries nothing.
        }
        at = buffer.indexOf('\n\n');
      }
    }
    buffer += decoder.decode();
    if (buffer.trim() !== '') {
      for (const line of buffer.split('\n')) {
        if (!line.startsWith('data:')) continue;
        const raw = line.slice(5).trim();
        if (raw === '' || raw === '[DONE]') continue;
        try {
          yield { event: null, data: JSON.parse(raw) };
        } catch {
          // Ignore.
        }
      }
    }
  } finally {
    reader.releaseLock();
  }
}

/** One OpenAI chat chunk: the delta, the finish reason, and the usage when it is the last one. */
function openAIChunk(model: string, delta: Json, finish: string | null, usage: Json | null): string {
  const chunk: Json = { id: 'chatcmpl-aggregate', object: 'chat.completion.chunk', created: FIXED_OPENAI_CREATED, model, choices: [{ index: 0, delta, finish_reason: finish }] };
  if (usage !== null) chunk.usage = usage;
  return `data: ${JSON.stringify(chunk)}\n\n`;
}

/**
 * An Anthropic SSE stream as OpenAI chat chunks: text deltas become content deltas, tool_use
 * blocks become tool_calls deltas, message_delta carries the stop reason and the usage.
 */
export async function* openAIEventsFromAnthropic(upstream: ReadableStream<Uint8Array>, model: string): AsyncGenerator<string> {
  let sentRole = false;
  let inputTokens = 0;
  let outputTokens = 0;
  let stopReason: string | null = null;
  const toolIndexes = new Map<number, number>();
  for await (const frame of sseFrames(upstream)) {
    if (frame.data === '[DONE]') break;
    if (!isRecord(frame.data)) continue;
    const data = frame.data;
    if (frame.event === 'message_start' && isRecord(data.message) && isRecord(data.message.usage)) {
      inputTokens = numberOrZero(data.message.usage.input_tokens);
      continue;
    }
    if (frame.event === 'content_block_delta' && isRecord(data.delta)) {
      const delta = data.delta;
      if (!sentRole) {
        sentRole = true;
        yield openAIChunk(model, { role: 'assistant', content: '' }, null, null);
      }
      if (delta.type === 'text_delta' && typeof delta.text === 'string' && delta.text !== '') {
        yield openAIChunk(model, { content: delta.text }, null, null);
      } else if (delta.type === 'input_json_delta' && typeof delta.partial_json === 'string' && delta.partial_json !== '') {
        const index = typeof data.index === 'number' ? data.index : 0;
        const toolIndex = toolIndexes.get(index) ?? index;
        yield openAIChunk(model, { tool_calls: [{ index: toolIndex, function: { arguments: delta.partial_json } }] }, null, null);
      }
      continue;
    }
    if (frame.event === 'content_block_start' && isRecord(data.content_block)) {
      const block = data.content_block;
      const index = typeof data.index === 'number' ? data.index : 0;
      if (!sentRole) {
        sentRole = true;
        yield openAIChunk(model, { role: 'assistant', content: '' }, null, null);
      }
      if (block.type === 'tool_use') {
        toolIndexes.set(index, toolIndexes.size);
        yield openAIChunk(model, { tool_calls: [{ index: toolIndexes.get(index), id: typeof block.id === 'string' ? block.id : 'call_unknown', type: 'function', function: { name: typeof block.name === 'string' ? block.name : '', arguments: '' } }] }, null, null);
      }
      continue;
    }
    if (frame.event === 'message_delta') {
      if (isRecord(data.delta) && typeof data.delta.stop_reason === 'string') stopReason = anthropicStopToOpenAI(data.delta.stop_reason);
      if (isRecord(data.usage)) outputTokens = numberOrZero(data.usage.output_tokens);
      continue;
    }
  }
  if (!sentRole) yield openAIChunk(model, { role: 'assistant', content: '' }, null, null);
  yield openAIChunk(model, {}, stopReason ?? 'stop', { prompt_tokens: inputTokens, completion_tokens: outputTokens, total_tokens: inputTokens + outputTokens });
  yield 'data: [DONE]\n\n';
}

/**
 * A Gemini :streamGenerateContent SSE stream as OpenAI chat chunks: each frame's text pieces
 * become content deltas, the final frame carries the finish reason and the usage.
 */
export async function* openAIEventsFromGemini(upstream: ReadableStream<Uint8Array>, model: string): AsyncGenerator<string> {
  let sentRole = false;
  let inputTokens = 0;
  let outputTokens = 0;
  let finish: string | null = null;
  for await (const frame of sseFrames(upstream)) {
    if (frame.data === '[DONE]') break;
    if (!isRecord(frame.data)) continue;
    const data = frame.data;
    const candidates = Array.isArray(data.candidates) ? data.candidates : [];
    const candidate = isRecord(candidates[0]) ? candidates[0] : {};
    const content = isRecord(candidate.content) ? candidate.content : {};
    const parts = Array.isArray(content.parts) ? content.parts : [];
    const text = parts.flatMap((p) => (isRecord(p) && typeof p.text === 'string' ? [p.text] : [])).join('');
    if (text !== '') {
      if (!sentRole) {
        sentRole = true;
        yield openAIChunk(model, { role: 'assistant', content: '' }, null, null);
      }
      yield openAIChunk(model, { content: text }, null, null);
    }
    if (typeof candidate.finishReason === 'string') finish = geminiFinishToOpenAI(candidate.finishReason);
    if (isRecord(data.usageMetadata)) {
      inputTokens = numberOrZero(data.usageMetadata.promptTokenCount);
      outputTokens = numberOrZero(data.usageMetadata.candidatesTokenCount);
    }
  }
  if (!sentRole) yield openAIChunk(model, { role: 'assistant', content: '' }, null, null);
  yield openAIChunk(model, {}, finish ?? 'stop', { prompt_tokens: inputTokens, completion_tokens: outputTokens, total_tokens: inputTokens + outputTokens });
  yield 'data: [DONE]\n\n';
}

/**
 * A Gemini :streamGenerateContent SSE stream as the Anthropic event sequence: the first text
 * opens message_start and a text block, pieces become text deltas, the final frame closes the
 * block and sends message_delta with the stop reason and usage, then message_stop.
 */
export async function* anthropicEventsFromGemini(upstream: ReadableStream<Uint8Array>, model: string): AsyncGenerator<string> {
  let started = false;
  let textIndex = -1;
  let nextIndex = 0;
  let inputTokens = 0;
  let outputTokens = 0;
  let stopReason = 'end_turn';
  const startEvents = (): string[] => {
    if (started) return [];
    started = true;
    return [
      sseEvent('message_start', {
        type: 'message_start',
        message: { id: 'msg_stream', type: 'message', role: 'assistant', model, content: [], stop_reason: null, stop_sequence: null, usage: { input_tokens: inputTokens, output_tokens: 0 } },
      }),
    ];
  };
  for await (const frame of sseFrames(upstream)) {
    if (frame.data === '[DONE]') break;
    if (!isRecord(frame.data)) continue;
    const data = frame.data;
    const candidates = Array.isArray(data.candidates) ? data.candidates : [];
    const candidate = isRecord(candidates[0]) ? candidates[0] : {};
    const content = isRecord(candidate.content) ? candidate.content : {};
    const parts = Array.isArray(content.parts) ? content.parts : [];
    const text = parts.flatMap((p) => (isRecord(p) && typeof p.text === 'string' ? [p.text] : [])).join('');
    if (text !== '') {
      const out: string[] = [...startEvents()];
      if (textIndex === -1) {
        textIndex = nextIndex;
        nextIndex += 1;
        out.push(sseEvent('content_block_start', { type: 'content_block_start', index: textIndex, content_block: { type: 'text', text: '' } }));
      }
      out.push(sseEvent('content_block_delta', { type: 'content_block_delta', index: textIndex, delta: { type: 'text_delta', text } }));
      for (const event of out) yield event;
    }
    if (typeof candidate.finishReason === 'string') stopReason = geminiFinishToAnthropic(candidate.finishReason);
    if (isRecord(data.usageMetadata)) {
      inputTokens = numberOrZero(data.usageMetadata.promptTokenCount);
      outputTokens = numberOrZero(data.usageMetadata.candidatesTokenCount);
    }
  }
  const out: string[] = [...startEvents()];
  if (textIndex !== -1) {
    out.push(sseEvent('content_block_stop', { type: 'content_block_stop', index: textIndex }));
    textIndex = -1;
  }
  out.push(
    sseEvent('message_delta', { type: 'message_delta', delta: { stop_reason: stopReason, stop_sequence: null }, usage: { output_tokens: outputTokens } }),
    sseEvent('message_stop', { type: 'message_stop' }),
  );
  for (const event of out) yield event;
}
